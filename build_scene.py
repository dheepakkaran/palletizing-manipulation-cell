"""Writes scene/cell.xml: Panda + vacuum tool, conveyor pick zone, pallet, 12 free case bodies,
one (inactive) weld equality per case = the vacuum grip, two fixed overhead RGB-D cameras."""
from __future__ import annotations

from pathlib import Path

from cases import case_bodies

ROOT = Path(__file__).resolve().parent
PALLET_CENTER = (0.42, -0.27)
PALLET_TOP = 0.10
PICK_XY = (0.45, 0.35)
CONVEYOR_TOP = 0.10
PARK_X = -0.9  # cases wait here (off to the side, out of reach) until fed to the pick spot


def park_pos(i: int):
    return (PARK_X - 0.2 * (i // 4), -0.45 + 0.3 * (i % 4), 0.06)


def build() -> str:
    cases, welds = [], []
    for i, (name, ct) in enumerate(case_bodies()):
        hx, hy, hz = (s / 2 for s in ct.size)
        px, py, _ = park_pos(i)
        r, g, b, a = ct.rgba
        cases.append(
            f'    <body name="{name}" pos="{px} {py} {hz + 0.001}">\n'
            f'      <freejoint name="{name}_jnt"/>\n'
            f'      <geom name="{name}_geom" type="box" size="{hx} {hy} {hz}" mass="{ct.mass}" '
            f'rgba="{r} {g} {b} {a}" friction="0.8 0.01 0.001"/>\n'
            f'    </body>')
        welds.append(f'    <weld name="suck_{name}" body1="tool" body2="{name}" active="false" solref="0.01 1"/>')
    pcx, pcy = PALLET_CENTER
    kx, ky = PICK_XY
    return f"""<!-- Mixed-case palletizing cell (simulation only). Generated by build_scene.py.
     Franka Panda (MuJoCo Menagerie, Apache-2.0) with a vacuum pad tool. Units: metres. Robot base at the origin. -->
<mujoco model="palletizing_cell">
  <include file="panda_suction.xml"/>
  <compiler meshdir="../assets/franka_emika_panda/assets"/>
  <option timestep="0.002" integrator="implicitfast"/>
  <visual>
    <headlight diffuse="0.6 0.6 0.6" ambient="0.35 0.35 0.35" specular="0 0 0"/>
    <global offwidth="640" offheight="480"/>
    <map znear="0.05" zfar="5"/>
  </visual>
  <worldbody>
    <light name="top" pos="0.4 0 2.0" dir="0 0 -1" diffuse="0.5 0.5 0.5"/>
    <geom name="floor" type="plane" size="3 3 0.1" rgba="0.55 0.55 0.55 1"/>
    <geom name="pallet" type="box" pos="{pcx} {pcy} {PALLET_TOP / 2}" size="0.16 0.235 {PALLET_TOP / 2}" rgba="0.75 0.6 0.35 1"/>
    <geom name="conveyor" type="box" pos="{kx} {ky} {CONVEYOR_TOP / 2}" size="0.12 0.25 {CONVEYOR_TOP / 2}" rgba="0.2 0.2 0.25 1"/>
    <camera name="pallet_cam" pos="{pcx} {pcy} 1.30" xyaxes="1 0 0 0 1 0" fovy="45"/>
    <camera name="pick_cam" pos="{kx + 0.35} {ky} 0.90" xyaxes="0 1 0 -0.8 0 0.35" fovy="45"/>
    <camera name="overview" pos="1.6 0.0 1.2" xyaxes="0 1 0 -0.5 0 0.85" fovy="50"/>
{chr(10).join(cases)}
  </worldbody>
  <equality>
{chr(10).join(welds)}
  </equality>
</mujoco>
"""


if __name__ == "__main__":
    (ROOT / "scene" / "cell.xml").write_text(build())
    print("wrote scene/cell.xml")
