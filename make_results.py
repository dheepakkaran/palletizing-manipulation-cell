"""Writes RESULTS.md from results/eval_summary.json and results/grasp_model.json (no hand-typed numbers)."""
import json
from pathlib import Path

R = Path(__file__).resolve().parent / "results"
s = json.loads((R / "eval_summary.json").read_text())
g = json.loads((R / "grasp_model.json").read_text())
cfg = s["config"]
pe, tl, gp, fl = s["placement_error_mm"], s["tilt_deg_from_depth"], s["min_gap_to_neighbour_mm"], s["layer_flatness_mm"]
vp, vf = s["rule_violations_planner"], s["rule_violations_first_fit_same_cases"]
drops = s["drops_by_cause"] or {"(none)": 0}
lines = [
    "# Results (simulation only)",
    "",
    "Generated by `make_results.py` from files in `results/`. Every number below is copied from those files.",
    "",
    f"## Randomized eval: `eval.py --pallets {cfg['pallets']} --seed {cfg['seed']}` (source: `results/eval_summary.json`)",
    f"Grasp model gating on: {cfg['grasp_model']}; pad positioning error sigma = {cfg['grasp_sigma_m']} m; wall time {cfg['wall_s']:.0f} s.",
    "",
    "| Metric | Value |",
    "|---|---|",
    f"| Pallets fully correct (every expected case placed, found by vision, stable after settle) | {s['pallet_success']} / {s['pallets']} = {s['pallet_success_rate']:.3f} |",
    f"| Cases ordered / missing injected / placed | {s['cases_ordered']} / {s['cases_missing_injected']} / {s['cases_placed']} |",
    f"| Drops by cause | {', '.join(f'{k}: {v}' for k, v in drops.items())} |",
    f"| All events | {', '.join(f'{k}: {v}' for k, v in s['events_by_type'].items()) or '(none)'} |",
    f"| Grasp-model flags (risky pick -> RETRY with a new pad position) | {s['grasp_model_flags']} |",
    f"| Unstable cases after settle (shift > 20 mm or tilt > 5 deg, simulator truth) | {s['unstable_cases']} |",
    f"| Cases not found by the pallet camera | {s['vision_not_found']} |",
    f"| Placement error from depth camera (mm), n = {pe['n']} | mean {pe['mean']:.2f}, median {pe['median']:.2f}, p95 {pe['p95']:.2f}, max {pe['max']:.2f} |",
    f"| Top-face tilt from depth plane fit (deg) | mean {tl['mean']:.3f}, p95 {tl['p95']:.3f}, max {tl['max']:.3f} |",
    f"| Min gap to a neighbour in the same layer (mm), n = {gp['n']} | mean {gp['mean']:.1f}, min {gp['min']:.1f} |",
    f"| Layer flatness (max - min top height per layer, mm), {fl['n_layers']} layers | mean {fl['mean']:.2f}, max {fl['max']:.2f} |",
    f"| Rule violations, planner (as built) | {vp.get('total', 0)} ({', '.join(f'{k} {v}' for k, v in vp.items() if k != 'total')}) |",
    f"| Rule violations, first-fit baseline on the same cases (checked, not executed) | {vf.get('total', 0)} ({', '.join(f'{k} {v}' for k, v in vf.items() if k != 'total')}) |",
    f"| Mean simulated time per pallet (s) | {s['sim_time_per_pallet_s_mean']:.1f} |",
    "",
    "## Grasp-risk model (source: `results/grasp_model.json`, data: `results/grasp_dataset.csv`)",
    "",
    "| Metric | Value |",
    "|---|---|",
    f"| Curated picks (train / held-out test) | {g['n_total']} ({g['n_train']} / {g['n_test']}) |",
    f"| Risky rate (seal fail or drop), all / test | {g['risky_rate_total']:.3f} / {g['risky_rate_test']:.3f} |",
    f"| Held-out accuracy, MLP ({g['model']}) | {g['heldout_accuracy_mlp']:.3f} |",
    f"| Held-out accuracy, offset rule ({g['rule']}) | {g['heldout_accuracy_rule']:.3f} |",
    f"| Held-out accuracy, always-majority | {g['heldout_accuracy_majority']:.3f} |",
    f"| MLP recall / precision on risky picks (test) | {g['mlp_recall_risky']:.3f} / {g['mlp_precision_risky']:.3f} |",
    "",
    "Labels come from this simulator's vacuum model (see `sim.py`), so the model learns the simulator, not a real gripper.",
]
if (R / "failure_breakdown.json").exists():
    fb = json.loads((R / "failure_breakdown.json").read_text())
    lines += ["", "## Why pallets failed (source: `results/failure_breakdown.json`)", "",
              f"{fb['failed_pallets']} failed pallets; reasons per failed pallet: "
              + ", ".join(f"{k} {v}" for k, v in fb["reasons_per_failed_pallet"].items()) + "."]
if (R / "pytest.txt").exists():
    lines += ["", "## Tests (source: `results/pytest.txt`)", "", "```", (R / "pytest.txt").read_text().strip().splitlines()[-1], "```"]
(R.parent / "RESULTS.md").write_text("\n".join(lines) + "\n")
print("wrote RESULTS.md")
